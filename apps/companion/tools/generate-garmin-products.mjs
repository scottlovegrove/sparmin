// Regenerates src/lib/garmin-products.ts from the Connect IQ SDK's device
// metadata.
//
// The watch sends System.getDeviceSettings().partNumber — "006-B4426-00" — which
// is the only product identifier Connect IQ offers an app. It is meaningless to
// the person reading their own device list, and there is no API that turns it
// into a name, so the mapping has to be shipped.
//
// Every device the SDK knows carries a displayName and the part numbers it ships
// under, in ~/.Garmin/ConnectIQ/Devices/<device>/compiler.json. A device usually
// has several part numbers (regional and firmware variants), all of the same
// hardware, so the map is many-to-one.
//
//   node tools/generate-garmin-products.mjs
//
// Run it after an SDK update, when a device new enough to be unknown starts
// showing up as a bare part number. Nothing breaks without it — an unmapped part
// number is displayed as-is.

import { readdir, readFile, writeFile } from 'node:fs/promises'
import { homedir } from 'node:os'
import { join } from 'node:path'

const DEVICES = join(homedir(), '.Garmin', 'ConnectIQ', 'Devices')
const OUT = new URL('../src/lib/garmin-products.ts', import.meta.url)

// Garmin writes its marketing names with trademark marks — "vívoactive® 5",
// "fēnix® 8". They are noise in a settings list, and the accented characters
// that carry the brand are kept.
function clean(name) {
    return name
        .replace(/[®™]/g, '')
        .replace(/\s+/g, ' ')
        .trim()
}

const entries = new Map()

for (const dir of await readdir(DEVICES)) {
    let device
    try {
        device = JSON.parse(await readFile(join(DEVICES, dir, 'compiler.json'), 'utf8'))
    } catch {
        continue
    }
    const name = device.displayName == null ? null : clean(device.displayName)
    if (name == null || name === '') {
        continue
    }
    const numbers = [
        ...(device.partNumbers ?? []).map((part) => part.number),
        device.worldWidePartNumber,
    ]
    for (const number of numbers) {
        // First writer wins, so a device folder cannot quietly reassign a part
        // number another already claimed.
        if (typeof number === 'string' && number !== '' && !entries.has(number)) {
            entries.set(number, name)
        }
    }
}

const sorted = [...entries].sort(([a], [b]) => a.localeCompare(b))

const body = sorted.map(([number, name]) => `    '${number}': ${JSON.stringify(name)},`).join('\n')

await writeFile(
    OUT,
    `// Generated by tools/generate-garmin-products.mjs from the Connect IQ SDK.
// Do not edit by hand — re-run the generator after an SDK update.
//
// Connect IQ gives an app only its device's part number, so this is what turns
// "006-B4426-00" into "vívoactive 5" in the watch list.

export const GARMIN_PRODUCTS: Readonly<Record<string, string>> = {
${body}
}
`,
)

console.log(`${sorted.length} part numbers → ${OUT.pathname}`)
